SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS books (
    id          INTEGER PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    author      VARCHAR(100) NOT NULL,
    category    VARCHAR(50)  NOT NULL,
    total_count INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS borrow_records (
    id          INTEGER PRIMARY KEY,
    book_id     INTEGER NOT NULL,
    reader_name VARCHAR(100) NOT NULL,
    borrow_date DATE    NOT NULL,
    return_date DATE,
    FOREIGN KEY (book_id) REFERENCES books(id)
);

CREATE TABLE IF NOT EXISTS readers (
    id      INTEGER PRIMARY KEY,
    name    VARCHAR(100) NOT NULL,
    card_no VARCHAR(50)  NOT NULL UNIQUE,
    phone   VARCHAR(20)
);
"""


def init_db(db_path: str, category: str) -> None:
    """初始化本地 SQLite 数据库文件。

    - 若文件已存在则先删除，确保每次启动都是干净的演示数据。
    - 创建表结构并插入该分类的 books、对应的 borrow_records、以及完整的 readers 表。
    """
    # 为了保证每次启动都有一致的数据，先删旧文件
    if os.path.exists(db_path):
        os.remove(db_path)

    conn = sqlite3.connect(db_path)
    try:
        conn.executescript(SCHEMA_SQL)

        # 插入 books
        for row in BOOK_SEEDS.get(category, []):
            conn.execute(
                "INSERT INTO books (id, title, author, category, total_count) VALUES (?, ?, ?, ?, ?)",
                row,
            )

        # 插入 borrow_records
        for row in BORROW_SEEDS.get(category, []):
            conn.execute(
                "INSERT INTO borrow_records (id, book_id, reader_name, borrow_date, return_date) VALUES (?, ?, ?, ?, ?)",
                row,
            )

        # readers 全量副本
        for row in READER_SEEDS:
            conn.execute(
                "INSERT INTO readers (id, name, card_no, phone) VALUES (?, ?, ?, ?)",
                row,
            )

        conn.commit()
    finally:
        conn.close()


@contextmanager
def get_conn(db_path: str) -> Iterator[sqlite3.Connection]:
    """获取一个 sqlite3 连接的上下文管理器，启用 row_factory。"""
    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    try:
        yield conn
    finally:
        conn.close()


def execute_sql(db_path: str, sql: str) -> Tuple[List[str], List[List]]:
    """在本地数据库执行一条 SQL（只支持只读查询）。

    返回 (columns, rows) 两个列表，rows 中每一行也是一个列表。
    非法 SQL 或写操作会抛出异常，由调用方处理。
    """
    with get_conn(db_path) as conn:
        cur = conn.execute(sql)
        columns = [d[0] for d in cur.description] if cur.description else []
        rows = [list(r) for r in cur.fetchall()]
        return columns, rows
